function Locale:RegisterStrings(localeCode, strings)
    local merged = {}
    local base = self.Strings[localeCode] or self.Strings.enUS or baseStrings
    for key, value in pairs(base) do
        merged[key] = value
    end
    for key, value in pairs(strings or {}) do
        merged[key] = value
    end
    self.Strings[localeCode] = merged
    if localeCode == self:GetCurrentCode() then
        self.CurrentCode = localeCode
        self.Current = merged
    end
end

function Locale:GetSavedOverride()
    if type(_G.WidgetForgeDB) == "table" and type(_G.WidgetForgeDB.localeOverride) == "string" and _G.WidgetForgeDB.localeOverride ~= "" then
        return _G.WidgetForgeDB.localeOverride
    end
    return nil
end

function Locale:GetClientCode()
    self.ClientCode = (GetLocale and GetLocale()) or self.ClientCode or "enUS"
    return self.ClientCode
end

function Locale:GetCurrentCode()
    local code = self:GetSavedOverride() or self:GetClientCode() or "enUS"
    if not self.Strings[code] then
        code = "enUS"
    end
    return code
end

function Locale:RefreshCurrent()
    local code = self:GetCurrentCode()
    if self.CurrentCode ~= code or not self.Current then
        self.CurrentCode = code
        self.Current = self.Strings[code] or self.Strings.enUS or baseStrings
    end
    return self.CurrentCode, self.Current
end

function Locale:GetSupportedCodes()
    local codes = {}
    for code in pairs(self.Strings) do
        codes[#codes + 1] = code
    end
    table.sort(codes)
    return codes
end

function Locale:NormalizeCode(localeCode)
    if type(localeCode) ~= "string" or localeCode == "" then
        return nil
    end
    for _, code in ipairs(self:GetSupportedCodes()) do
        if string.lower(code) == string.lower(localeCode) then
            return code
        end
    end
    return nil
end

function Locale:SetOverride(localeCode)
    local resolved = self:NormalizeCode(localeCode)
    if not resolved then
        return false
    end
    _G.WidgetForgeDB = _G.WidgetForgeDB or {}
    _G.WidgetForgeDB.localeOverride = resolved
    self:RefreshCurrent()
    return true, resolved
end

function Locale:ClearOverride()
    if type(_G.WidgetForgeDB) == "table" then
        _G.WidgetForgeDB.localeOverride = nil
    end
    self:RefreshCurrent()
end

local function FormatText(text, ...)
    if select("#", ...) == 0 then
        return text
    end
    local ok, formatted = pcall(string.format, text, ...)
    if ok then
        return formatted
    end
    return text
end

function Locale:GetText(key, fallback)
    local _, current = self:RefreshCurrent()
    return current[key] or baseStrings[key] or fallback or key
end

function Locale:GetElementName(typeName, useShortName)
    if not typeName then
        return ""
    end
    local keyMap = useShortName and self.ShortElementKeys or self.ElementKeys
    local lookupKey = keyMap[typeName] or self.ElementKeys[typeName]
    if not lookupKey then
        return typeName
    end
    return self:GetText(lookupKey, typeName)
end

function Locale:GetWidgetName(typeID, fallback)
    local lookupKey = self.WidgetNameKeys[typeID]
    if not lookupKey then
        return fallback or typeID
    end
    return self:GetText(lookupKey, fallback or typeID)
end

function Locale:GetWidgetDescription(typeID, fallback)
    local lookupKey = self.WidgetDescriptionKeys[typeID]
    if not lookupKey then
        return fallback or typeID
    end
    return self:GetText(lookupKey, fallback or typeID)
end

Locale:RegisterStrings("enUS", baseStrings)
Locale:RefreshCurrent()

function WFL(key, ...)
    return FormatText(Locale:GetText(key), ...)
end

function WFL_ELEMENT(typeName, useShortName)
    return Locale:GetElementName(typeName, useShortName)
end

function WFL_WIDGET(typeID, fallback)
    return Locale:GetWidgetName(typeID, fallback)
end

function WFL_WIDGET_DESC(typeID, fallback)
    return Locale:GetWidgetDescription(typeID, fallback)
end
